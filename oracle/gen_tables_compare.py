"""Generate the tables rsympy-core's canonical ordering and str printer
dispatch on, from the pinned SymPy.

    PYTHONHASHSEED=0 SYMPY_GROUND_TYPES=python .venv/bin/python oracle/gen_tables_compare.py

Writes crates/rsympy-core/src/generated_compare.rs. For every class in
oracle/gen_core_tables.py's CLASSES (the `ClassId` order) it records, read
off the live classes:

- `cls.class_key()`, all three entries (Number subclasses say 'Number');
- which class in the MRO defines `sort_key`, `_hashable_content`,
  `compare`, `_sorted_args`, `as_ordered_factors` and `as_ordered_terms`,
  so `compare.rs` runs the same method SymPy's attribute lookup finds;
- the `StrPrinter._print_<X>` method `Printer._print` dispatches to, with
  its AppliedUndef/UndefinedFunction/Function MRO exceptions (or the
  class's own `_sympystr`).

It also records `Function.class_key`'s `funcs` table, found by probing
`Function(name).class_key()` for the names in the method's constants, and
the values it falls back to for `nargs` being `Naturals0` or not.

CI regenerates the file and fails if it differs from what is committed.
"""

import pathlib
import subprocess

import sympy as sp
from sympy.core.function import AppliedUndef, Function, UndefinedFunction
from sympy.external.gmpy import GROUND_TYPES
from sympy.printing.str import StrPrinter

from gen_core_tables import CLASSES

assert sp.__version__ == "1.14.0", sp.__version__
assert GROUND_TYPES == "python", "set SYMPY_GROUND_TYPES=python"

OUT = (pathlib.Path(__file__).parent.parent / "crates" / "rsympy-core" / "src"
       / "generated_compare.rs")

ATTRS = ["sort_key", "_hashable_content", "compare", "_sorted_args",
         "as_ordered_factors", "as_ordered_terms"]


def owner(cls, attr):
    """`Class.attr` for the class in `cls`'s MRO that defines `attr`, or ''."""
    for k in cls.__mro__:
        if attr in vars(k):
            return f"{k.__name__}.{attr}"
    return ""


def str_print_method(cls):
    """The method `Printer._print` (sympy/printing/printer.py) picks for an
    instance of `cls` under StrPrinter: `Class._sympystr` when the object
    prints itself, else a `_print_<X>` method name."""
    if hasattr(cls, StrPrinter.printmethod):
        return owner(cls, StrPrinter.printmethod)
    classes = cls.__mro__
    if AppliedUndef in classes:
        classes = classes[classes.index(AppliedUndef):]
    if UndefinedFunction in classes:
        classes = classes[classes.index(UndefinedFunction):]
    if Function in classes:
        i = classes.index(Function)
        classes = tuple(c for c in classes[:i] if
                        c.__name__ == classes[0].__name__ or
                        c.__name__.endswith("Base")) + classes[i:]
    for c in classes:
        name = "_print_" + c.__name__
        if getattr(StrPrinter, name, None) is not None:
            return name
    return "emptyPrinter"


def function_class_key_funcs():
    """`funcs` in `Function.class_key`, probed name by name."""
    probe = "rsympy_probe_name"
    naturals0 = Function(probe).class_key()[1]
    other = Function(probe, nargs=1).class_key()[1]
    names = set()
    for c in Function.class_key.__func__.__code__.co_consts:
        if isinstance(c, tuple):
            names.update(x for x in c if isinstance(x, str))
    table = []
    for name in sorted(names):
        i = Function(name).class_key()[1]
        if i != naturals0:
            table.append((name, i))
    # Every listed name keeps its value whatever nargs is.
    for name, i in table:
        assert Function(name, nargs=1).class_key()[1] == i, name
    return table, naturals0, other


def rust_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def lines():
    out = ["// @generated by oracle/gen_tables_compare.py from SymPy 1.14.0. Do not edit.", ""]
    out.append("use crate::generated::NUM_CLASSES;")
    out.append("")
    out.append("/// What `compare.rs` and `printing/str.rs` dispatch on, per class.")
    out.append("pub(crate) struct CompareInfo {")
    out.append("    /// `cls.class_key()`.")
    out.append("    pub class_key: (i32, i32, &'static str),")
    for attr in ATTRS:
        out.append(f"    /// The `Class.{attr}` that attribute lookup finds (\"\" if none).")
        out.append(f"    pub {attr.lstrip('_')}: &'static str,")
    out.append("    /// The `StrPrinter` method `Printer._print` dispatches to.")
    out.append("    pub str_print: &'static str,")
    out.append("}")
    out.append("")
    out.append("/// Indexed by `ClassId`.")
    out.append("pub(crate) const COMPARE_INFO: [CompareInfo; NUM_CLASSES] = [")
    for name, cls in CLASSES:
        ck = cls.class_key()
        out.append(f"    // {name}")
        out.append("    CompareInfo {")
        out.append(f"        class_key: ({ck[0]}, {ck[1]}, {rust_str(ck[2])}),")
        for attr in ATTRS:
            out.append(f"        {attr.lstrip('_')}: {rust_str(owner(cls, attr))},")
        out.append(f"        str_print: {rust_str(str_print_method(cls))},")
        out.append("    },")
    out.append("];")
    out.append("")
    table, naturals0, other = function_class_key_funcs()
    out.append("/// `funcs` in `Function.class_key`: `class_key()[1]` by class name.")
    out.append("pub(crate) const FUNCTION_CLASS_KEY_FUNCS: &[(&str, i32)] = &[")
    out.extend(f"    ({rust_str(n)}, {i})," for n, i in table)
    out.append("];")
    out.append("")
    out.append("/// `Function.class_key()[1]` for other names when `nargs` is `Naturals0`.")
    out.append(f"pub(crate) const FUNCTION_CLASS_KEY_NATURALS0: i32 = {naturals0};")
    out.append("")
    out.append("/// `Function.class_key()[1]` for other names and any other `nargs`.")
    out.append(f"pub(crate) const FUNCTION_CLASS_KEY_OTHER: i32 = {other};")
    out.append("")
    return out


if __name__ == "__main__":
    OUT.write_text("\n".join(lines()))
    subprocess.run(["rustfmt", "--edition", "2024", str(OUT)], check=True)
    print(f"wrote {OUT}")
