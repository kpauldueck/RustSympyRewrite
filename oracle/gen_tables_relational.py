"""Generate the dispatch tables rsympy-core's relational and boolalg ports
read, from the pinned SymPy.

    PYTHONHASHSEED=0 SYMPY_GROUND_TYPES=python .venv/bin/python oracle/gen_tables_relational.py

Writes crates/rsympy-core/src/generated_relational.rs. For every pair of
classes in oracle/gen_core_tables.py's CLASSES it records, read off the
live objects:

- which function the multipledispatch `Dispatcher`s `_eval_is_eq` and
  `_eval_is_ge` (sympy/core/relational.py and the modules that register
  more signatures on them) resolve `(type(lhs), type(rhs))` to, named by
  the module that registered it and the signature it was registered
  under, e.g. `relational(Tuple, Expr)` (`_eval_is_ge` has no
  implementation for non-Expr types, which `is_ge` rejects before it
  dispatches);
- which classes are proper subclasses of which, because Python's
  comparison operators try the right operand's reflected method first
  when its type is a proper subclass of the left operand's.

CI regenerates the file and fails if it differs from what is committed.
"""

import pathlib
import subprocess
import warnings

import sympy as sp
from sympy.core.relational import _eval_is_eq, _eval_is_ge
from sympy.external.gmpy import GROUND_TYPES

from gen_core_tables import CLASSES

assert sp.__version__ == "1.14.0", sp.__version__
assert GROUND_TYPES == "python", "set SYMPY_GROUND_TYPES=python"

OUT = (pathlib.Path(__file__).parent.parent / "crates" / "rsympy-core" / "src"
       / "generated_relational.rs")


def label(dispatcher, func):
    """`module(Type1, Type2)`: the module that registered `func` on
    `dispatcher` and the signature it registered it under."""
    sigs = [sig for sig, f in dispatcher.funcs.items() if f is func]
    assert len(sigs) == 1, (dispatcher.name, func, sigs)
    module = func.__module__.rsplit(".", 1)[-1]
    if func.__module__ == "sympy.sets.handlers.comparison":
        module = "sets"
    return f"{module}({', '.join(t.__name__ for t in sigs[0])})"


DIGITS = "0123456789abcdefghijklmnopqrstuvwxyz"


def table(dispatcher, default_sig):
    """The implementations `dispatcher` has (the default first, then in
    registration order) and, for each lhs class, a row with one digit per
    rhs class: the index of the implementation it resolves to, or `-` for
    none."""
    default = dispatcher.funcs[default_sig]
    impls = [default] + [f for f in dispatcher.funcs.values() if f is not default]
    rows = []
    for _, a in CLASSES:
        row = ""
        for _, b in CLASSES:
            with warnings.catch_warnings():
                warnings.simplefilter("error")
                func = dispatcher.dispatch(a, b)
            if func is None:
                # no implementation at all: only for pairs `is_ge`
                # rejects before dispatching (both sides must be Expr)
                assert not (issubclass(a, sp.Expr) and issubclass(b, sp.Expr))
                row += "-"
            else:
                row += DIGITS[impls.index(func)]
        rows.append(row)
    return [label(dispatcher, f) for f in impls], rows


def lines():
    out = ["// @generated by oracle/gen_tables_relational.py from SymPy 1.14.0. Do not edit.", ""]
    out.append("use crate::generated::{ClassId, NUM_CLASSES};")
    out.append("")
    for name, d, default in [("EVAL_IS_EQ", _eval_is_eq, (sp.Basic, sp.Basic)),
                             ("EVAL_IS_GE", _eval_is_ge, (sp.Expr, sp.Expr))]:
        labels, rows = table(d, default)
        out.append(f"/// The implementations registered on `{d.name}`, the default first.")
        out.append(f"pub(crate) const {name}_IMPLS: &[&str] = &[")
        out.extend(f'    "{lab}",' for lab in labels)
        out.append("];")
        out.append("")
        out.append(f"/// `{d.name}.dispatch(type(lhs), type(rhs))`: row `lhs as usize`, column")
        out.append(f"/// `rhs as usize` holds the index into `{name}_IMPLS` in base 36 (`-`: no")
        out.append("/// implementation).")
        out.append(f"pub(crate) const {name}: [&str; NUM_CLASSES] = [")
        for (cname, _), row in zip(CLASSES, rows):
            out.append(f'    "{row}", // {cname}')
        out.append("];")
        out.append("")
    out.append("/// `(sub, base)`: `sub` is a proper subclass of `base`.")
    out.append("pub(crate) const PROPER_SUBCLASSES: &[(ClassId, ClassId)] = &[")
    for a_name, a in CLASSES:
        for b_name, b in CLASSES:
            if a is not b and issubclass(a, b):
                out.append(f"    (ClassId::{a_name}, ClassId::{b_name}),")
    out.append("];")
    out.append("")
    return out


if __name__ == "__main__":
    OUT.write_text("\n".join(lines()))
    subprocess.run(["rustfmt", "--edition", "2024", str(OUT)], check=True)
    print(f"wrote {OUT}")
